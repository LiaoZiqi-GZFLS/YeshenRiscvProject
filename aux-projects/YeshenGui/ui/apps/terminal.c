/* Terminal: a real /bin/sh on a PTY, rendered into an LVGL text area.
 *
 * Keys are routed here by ui/app.c while the Terminal window is focused; the
 * shell owns every byte except Ctrl+W, which closes the window. The screen
 * model strips minimal ANSI and keeps 200 lines of scrollback. */
