#define TERM_ROWS 28
#define TERM_TIMER_MS 20
#define TERM_PX_PER_COL 8
#define TERM_LINE_PX 22
#define OSK_HEIGHT 236
#define OSK_TOOLBAR_H 34
/* Noto Sans Mono CJK SC, GB2312+ASCII, generated by lv_font_conv.
 * ASCII is half-width (8 px) so the 100x8 grid stays aligned; hanzi is 16 px. */
extern const lv_font_t lv_font_cjk_16;

#define TERM_BG 0x0B0F14u
#define TERM_FG 0xE6EDF3u
#define TERM_KEY_BG 0x1F2937u

typedef struct {
    ui_window_t *win;
    lv_obj_t *content;
    lv_obj_t *scroll;
    lv_obj_t *label;
    lv_obj_t *osk_box;
    lv_obj_t *kb;
    lv_obj_t *cursor;
    lv_obj_t *input_label;
    char input[TERM_COLS + 1];
    int input_len;
    int input_cur;
    lv_timer_t *timer;
    term_screen_t *screen;
    int master;
    pid_t pid;
    int rows;
    bool child_done;
    bool osk_shown;
    bool osk_user_hidden;
    bool was_focused;
    lv_keyboard_mode_t osk_mode;
} term_ctx_t;

static term_ctx_t *s_term;

static void terminal_refresh(term_ctx_t *c)
{
    if (!c || !c->label) return;
    lv_label_set_text(c->label, term_screen_text(c->screen));
    if (c->input_label) {
        int row = 0, col = 0;
        term_screen_cursor(c->screen, &row, &col);
        int x = col * TERM_PX_PER_COL;
        int y = row * TERM_LINE_PX;
        lv_label_set_text(c->input_label, c->input);
        lv_obj_set_pos(c->input_label, x, y);
        lv_obj_set_pos(c->cursor,
                       x + c->input_cur * TERM_PX_PER_COL, y);
    }
    lv_obj_update_layout(c->scroll);
    lv_obj_scroll_to_y(c->scroll, LV_COORD_MAX, LV_ANIM_OFF);
}

static void feed_msg(term_ctx_t *c, const char *msg)
{
    term_screen_feed(c->screen, msg, strlen(msg));
}

static void terminal_pty_resize(term_ctx_t *c)
{
    if (!c || !c->scroll) return;
    lv_obj_update_layout(c->scroll);
    int rows = (int)((lv_obj_get_content_height(c->scroll) - 4) / TERM_LINE_PX);
    if (rows < 6) rows = 6;
    if (rows > 200) rows = 200;
    if (rows == c->rows) return;
    c->rows = rows;
    if (c->master >= 0) {
        struct winsize ws = { .ws_row = (unsigned short)rows, .ws_col = TERM_COLS };
        ioctl(c->master, TIOCSWINSZ, &ws);
    }
}

static void terminal_osk_show(term_ctx_t *c, bool show)
{
    if (!c || !c->osk_box || c->osk_shown == show) return;
    c->osk_shown = show;
    if (show) {
        lv_obj_update_layout(c->content);
        lv_coord_t h = lv_obj_get_content_height(c->content) - OSK_HEIGHT - 2;
        if (h < 96) h = 96;
        lv_obj_set_height(c->scroll, h);
        lv_obj_remove_flag(c->osk_box, LV_OBJ_FLAG_HIDDEN);
    } else {
        lv_obj_add_flag(c->osk_box, LV_OBJ_FLAG_HIDDEN);
        lv_obj_set_height(c->scroll, LV_PCT(100));
    }
    lv_obj_update_layout(c->content);
    terminal_pty_resize(c);
}

static void osk_send_type(ui_key_type_t type)
{
    ui_key_t key = { .type = type, .ch = 0 };
    terminal_handle_key(&key);
}

static void osk_hide_cb(lv_event_t *e)
{
    term_ctx_t *c = lv_event_get_user_data(e);
    if (!c) return;
    c->osk_user_hidden = true;
    terminal_osk_show(c, false);
}

static void osk_type_cb(lv_event_t *e)
{
    osk_send_type((ui_key_type_t)(uintptr_t)lv_event_get_user_data(e));
}

static void osk_kb_cb(lv_event_t *e)
{
    term_ctx_t *c = lv_event_get_user_data(e);
    lv_event_code_t code = lv_event_get_code(e);
    if (!c) return;
    if (code == LV_EVENT_READY) {
        osk_send_type(UI_KEY_ENTER);
        return;
    }
    if (code == LV_EVENT_CANCEL) {
        c->osk_user_hidden = true;
        terminal_osk_show(c, false);
        return;
    }
    if (code != LV_EVENT_VALUE_CHANGED || !c->kb) return;

    /* LVGL's own handler runs first and switches the layout for mode keys, so
     * the id in the event is the only reliable handle; comparing the mode
     * tells a layout switch apart from a real key at the same position. */
    const uint32_t *param = lv_event_get_param(e);
    uint32_t id = param ? *param : lv_keyboard_get_selected_button(c->kb);
    lv_keyboard_mode_t mode = lv_keyboard_get_mode(c->kb);
    bool mode_switch = mode != c->osk_mode;
    c->osk_mode = mode;
    if (mode_switch) return;

    const char *txt = lv_keyboard_get_button_text(c->kb, id);
    if (!txt || !*txt) return;
    /* OK and close are handled by LVGL/READY/CANCEL first. */
    if (!strcmp(txt, LV_SYMBOL_OK) || !strcmp(txt, LV_SYMBOL_CLOSE) ||
        !strcmp(txt, LV_SYMBOL_KEYBOARD)) {
        return;
    }
    if (!strcmp(txt, LV_SYMBOL_BACKSPACE)) { osk_send_type(UI_KEY_BACKSPACE); return; }
    if (!strcmp(txt, LV_SYMBOL_NEW_LINE)) { osk_send_type(UI_KEY_ENTER); return; }
    if (!strcmp(txt, LV_SYMBOL_LEFT)) { osk_send_type(UI_KEY_LEFT); return; }
    if (!strcmp(txt, LV_SYMBOL_RIGHT)) { osk_send_type(UI_KEY_RIGHT); return; }
    if (txt[1] == '\0') {
        ui_key_t key = { .type = UI_KEY_CHAR, .ch = txt[0] };
        terminal_handle_key(&key);
    }
}

static lv_obj_t *osk_tool_btn(lv_obj_t *bar, const char *text,
                              lv_event_cb_t cb, void *ud)
{
    lv_obj_t *b = lv_button_create(bar);
    lv_obj_set_width(b, LV_SIZE_CONTENT);
    lv_obj_set_height(b, OSK_TOOLBAR_H - 4);
    lv_obj_set_style_pad_hor(b, 9, 0);
    lv_obj_set_style_pad_ver(b, 0, 0);
    lv_obj_set_style_bg_color(b, lv_color_hex(TERM_KEY_BG), 0);
    lv_obj_set_style_bg_opa(b, LV_OPA_COVER, 0);
    lv_obj_set_style_border_width(b, 0, 0);
    lv_obj_set_style_radius(b, 5, 0);
    lv_obj_add_event_cb(b, cb, LV_EVENT_CLICKED, ud);
    lv_obj_t *l = lv_label_create(b);
    lv_label_set_text(l, text);
    lv_obj_set_style_text_color(l, lv_color_hex(TERM_FG), 0);
    lv_obj_center(l);
    return b;
}

static void terminal_build_osk(term_ctx_t *c)
{
    lv_obj_t *box = lv_obj_create(c->content);
    c->osk_box = box;
    lv_obj_set_size(box, LV_PCT(100), OSK_HEIGHT);
    lv_obj_align(box, LV_ALIGN_BOTTOM_MID, 0, 0);
    lv_obj_set_style_bg_color(box, lv_color_hex(0x111827), 0);
    lv_obj_set_style_bg_opa(box, LV_OPA_COVER, 0);
    lv_obj_set_style_border_width(box, 0, 0);
    lv_obj_set_style_radius(box, 6, 0);
    lv_obj_set_style_pad_all(box, 2, 0);
    lv_obj_remove_flag(box, LV_OBJ_FLAG_SCROLLABLE);

    lv_obj_t *bar = lv_obj_create(box);
    lv_obj_set_size(bar, LV_PCT(100), OSK_TOOLBAR_H);
    lv_obj_set_style_bg_opa(bar, LV_OPA_TRANSP, 0);
    lv_obj_set_style_border_width(bar, 0, 0);
    lv_obj_set_style_pad_all(bar, 0, 0);
    lv_obj_set_style_pad_column(bar, 4, 0);
    lv_obj_set_flex_flow(bar, LV_FLEX_FLOW_ROW);
    lv_obj_set_flex_align(bar, LV_FLEX_ALIGN_START, LV_FLEX_ALIGN_CENTER,
                          LV_FLEX_ALIGN_CENTER);
    osk_tool_btn(bar, "Hide", osk_hide_cb, c);
    osk_tool_btn(bar, "Ctrl+C", osk_type_cb, (void *)(uintptr_t)UI_KEY_CTRL_C);
    osk_tool_btn(bar, "Tab", osk_type_cb, (void *)(uintptr_t)UI_KEY_TAB);
    osk_tool_btn(bar, "Esc", osk_type_cb, (void *)(uintptr_t)UI_KEY_ESC);
    osk_tool_btn(bar, "Up", osk_type_cb, (void *)(uintptr_t)UI_KEY_UP);
    osk_tool_btn(bar, "Down", osk_type_cb, (void *)(uintptr_t)UI_KEY_DOWN);
    osk_tool_btn(bar, "Left", osk_type_cb, (void *)(uintptr_t)UI_KEY_LEFT);
    osk_tool_btn(bar, "Right", osk_type_cb, (void *)(uintptr_t)UI_KEY_RIGHT);

    c->kb = lv_keyboard_create(box);
    c->osk_mode = lv_keyboard_get_mode(c->kb);
    lv_obj_set_size(c->kb, LV_PCT(100), OSK_HEIGHT - OSK_TOOLBAR_H - 6);
    lv_obj_set_style_bg_color(c->kb, lv_color_hex(0x1B2430), 0);
    lv_obj_set_style_bg_opa(c->kb, LV_OPA_COVER, 0);
    lv_obj_set_style_text_font(c->kb, &lv_font_montserrat_16, 0);
    lv_obj_add_event_cb(c->kb, osk_kb_cb, LV_EVENT_VALUE_CHANGED, c);
    lv_obj_add_event_cb(c->kb, osk_kb_cb, LV_EVENT_READY, c);
    lv_obj_add_event_cb(c->kb, osk_kb_cb, LV_EVENT_CANCEL, c);
    lv_obj_add_flag(box, LV_OBJ_FLAG_HIDDEN);
}

static void terminal_sync_focus(term_ctx_t *c)
{
    const char *title = wm_focused_title();
    bool focused = title && !strcmp(title, "Terminal");
    if (focused && !c->was_focused) c->osk_user_hidden = false;
    c->was_focused = focused;
    if (c->cursor) {
        if (focused) lv_obj_remove_flag(c->cursor, LV_OBJ_FLAG_HIDDEN);
        else lv_obj_add_flag(c->cursor, LV_OBJ_FLAG_HIDDEN);
    }
    if (!focused) {
        if (c->osk_shown) terminal_osk_show(c, false);
        return;
    }
    if (!c->osk_user_hidden && !c->osk_shown) terminal_osk_show(c, true);
}

bool terminal_osk_press(const char *text)
{
    if (!s_term || !s_term->kb || !text) return false;
    for (uint32_t id = 0;; id++) {
        const char *t = lv_keyboard_get_button_text(s_term->kb, id);
        if (!t || !*t) return false;
        if (!strcmp(t, text)) {
            lv_buttonmatrix_set_selected_button(s_term->kb, id);
            lv_obj_send_event(s_term->kb, LV_EVENT_VALUE_CHANGED, NULL);
            return true;
        }
    }
}

static lv_obj_t *find_label(lv_obj_t *parent, const char *text)
{
    uint32_t n = lv_obj_get_child_count(parent);
    for (uint32_t i = 0; i < n; i++) {
        lv_obj_t *ch = lv_obj_get_child(parent, i);
        if (lv_obj_check_type(ch, &lv_label_class) &&
            !strcmp(lv_label_get_text(ch), text)) {
            return ch;
        }
        lv_obj_t *found = find_label(ch, text);
        if (found) return found;
    }
    return NULL;
}

bool terminal_osk_click(const char *text)
{
    if (!s_term || !s_term->osk_box || !s_term->osk_shown) return false;
    lv_obj_t *label = find_label(s_term->osk_box, text);
    if (!label) return false;
    lv_obj_send_event(lv_obj_get_parent(label), LV_EVENT_CLICKED, NULL);
    return true;
}

bool terminal_osk_visible(void)
{
    return s_term && s_term->osk_shown;
}

static void spawn_shell(term_ctx_t *c)
{
    int master = posix_openpt(O_RDWR | O_NOCTTY);
    if (master < 0) {
        feed_msg(c, "terminal: posix_openpt failed\n");
        return;
    }
    if (grantpt(master) != 0 || unlockpt(master) != 0) {
        close(master);
        feed_msg(c, "terminal: grantpt/unlockpt failed\n");
        return;
    }
    char slave[128];
    const char *name = ptsname(master);
    if (!name) {
        close(master);
        feed_msg(c, "terminal: ptsname failed\n");
        return;
    }
    snprintf(slave, sizeof(slave), "%s", name);

    struct winsize ws = { .ws_row = TERM_ROWS, .ws_col = TERM_COLS };
    ioctl(master, TIOCSWINSZ, &ws);

    pid_t pid = fork();
    if (pid < 0) {
        close(master);
        feed_msg(c, "terminal: fork failed\n");
        return;
    }
    if (pid == 0) {
        setsid();
        int sfd = open(slave, O_RDWR);
        if (sfd < 0) _exit(127);
        ioctl(sfd, TIOCSCTTY, 0);
        struct termios tio;
        if (tcgetattr(sfd, &tio) == 0) {
            tio.c_lflag &= ~(ECHO | ECHOE | ECHOK | ECHONL);
            tcsetattr(sfd, TCSANOW, &tio);
        }
        dup2(sfd, STDIN_FILENO);
        dup2(sfd, STDOUT_FILENO);
        dup2(sfd, STDERR_FILENO);
        if (sfd > 2) close(sfd);
        close(master);

        setenv("TERM", "dumb", 1);
        setenv("PS1", "# ", 1);
        const char *home = getenv("HOME");
        setenv("HOME", home && *home ? home : "/root", 1);
        setenv("PATH", "/sbin:/usr/sbin:/bin:/usr/bin", 1);
        setenv("LC_ALL", "C", 1);
        execl("/bin/sh", "sh", (char *)NULL);
        _exit(127);
    }

    int flags = fcntl(master, F_GETFL, 0);
    if (flags >= 0) fcntl(master, F_SETFL, flags | O_NONBLOCK);
    c->master = master;
    c->pid = pid;
}

static void terminal_timer_cb(lv_timer_t *t)
{
    term_ctx_t *c = (term_ctx_t *)lv_timer_get_user_data(t);
    if (!c) return;
    bool changed = false;

    terminal_sync_focus(c);

    if (c->master >= 0) {
        char buf[4096];
        for (;;) {
            ssize_t n = read(c->master, buf, sizeof(buf));
            if (n > 0) {
                term_screen_feed(c->screen, buf, (size_t)n);
                changed = true;
                continue;
            }
            if (n < 0 && (errno == EAGAIN || errno == EINTR)) break;
            close(c->master);
            c->master = -1;
            if (!c->child_done) {
                c->child_done = true;
                feed_msg(c, "\n[terminal closed]\n");
                changed = true;
            }
            break;
        }
    }

    if (c->pid > 0) {
        int status = 0;
        pid_t r = waitpid(c->pid, &status, WNOHANG);
        if (r == c->pid) {
            c->pid = 0;
            if (!c->child_done) {
                c->child_done = true;
                feed_msg(c, "\n[shell exited - Ctrl+W closes]\n");
                changed = true;
            }
            if (c->master >= 0) {
                close(c->master);
                c->master = -1;
            }
        }
    }

    if (changed) terminal_refresh(c);
}

static void terminal_cleanup(term_ctx_t *c)
{
    if (!c) return;
    if (c->timer) {
        lv_timer_delete(c->timer);
        c->timer = NULL;
    }
    if (c->master >= 0) {
        close(c->master);
        c->master = -1;
    }
    if (c->pid > 0) {
        kill(-c->pid, SIGHUP);
        kill(c->pid, SIGHUP);
        waitpid(c->pid, NULL, WNOHANG);
        c->pid = 0;
    }
    if (c->screen) {
        term_screen_free(c->screen);
        c->screen = NULL;
    }
    if (s_term == c) s_term = NULL;
    free(c);
}

static void terminal_on_close(ui_window_t *win)
{
    if (s_term && s_term->win == win) terminal_cleanup(s_term);
}

static void terminal_build_ui(term_ctx_t *c, lv_obj_t *content)
{
    c->content = content;
    lv_obj_set_style_pad_all(content, 2, 0);
    lv_obj_set_style_bg_color(content, lv_color_hex(TERM_BG), 0);
    lv_obj_set_style_bg_opa(content, LV_OPA_COVER, 0);
    lv_obj_remove_flag(content, LV_OBJ_FLAG_SCROLLABLE);

    c->scroll = lv_obj_create(content);
    lv_obj_set_size(c->scroll, LV_PCT(100), LV_PCT(100));
    lv_obj_set_style_bg_color(c->scroll, lv_color_hex(TERM_BG), 0);
    lv_obj_set_style_bg_opa(c->scroll, LV_OPA_COVER, 0);
    lv_obj_set_style_border_width(c->scroll, 0, 0);
    lv_obj_set_style_pad_all(c->scroll, 2, 0);
    lv_obj_set_scroll_dir(c->scroll, LV_DIR_VER);
    lv_obj_set_scrollbar_mode(c->scroll, LV_SCROLLBAR_MODE_AUTO);

    c->label = lv_label_create(c->scroll);
    lv_obj_set_pos(c->label, 0, 0);
    lv_obj_set_width(c->label, TERM_COLS * TERM_PX_PER_COL);
    lv_label_set_long_mode(c->label, LV_LABEL_LONG_CLIP);
    lv_label_set_text(c->label, "");
    lv_obj_set_style_text_font(c->label, &lv_font_cjk_16, 0);
    lv_obj_set_style_text_color(c->label, lv_color_hex(TERM_FG), 0);
    lv_obj_set_style_text_line_space(c->label, 0, 0);

    c->input_label = lv_label_create(c->scroll);
    lv_obj_set_pos(c->input_label, 0, 0);
    lv_label_set_long_mode(c->input_label, LV_LABEL_LONG_CLIP);
    lv_label_set_text(c->input_label, "");
    lv_obj_set_style_text_font(c->input_label, &lv_font_cjk_16, 0);
    lv_obj_set_style_text_color(c->input_label, lv_color_hex(TERM_FG), 0);
    lv_obj_set_style_text_line_space(c->input_label, 0, 0);

    c->cursor = lv_obj_create(c->scroll);
    lv_obj_remove_style_all(c->cursor);
    lv_obj_set_size(c->cursor, 2, TERM_LINE_PX);
    lv_obj_set_style_bg_color(c->cursor, lv_color_hex(TERM_FG), 0);
    lv_obj_set_style_bg_opa(c->cursor, LV_OPA_COVER, 0);
    lv_obj_remove_flag(c->cursor, LV_OBJ_FLAG_SCROLLABLE);
    lv_obj_remove_flag(c->cursor, LV_OBJ_FLAG_CLICKABLE);

    terminal_build_osk(c);
}

void terminal_open(void)
{
    if (s_term) {
        wm_focus(s_term->win);
        return;
    }

    lv_obj_t *content = NULL;
    ui_window_t *win = wm_open("Terminal", 900, 460, true, &content,
                               terminal_on_close);
    if (!win || !content) return;

    term_ctx_t *c = calloc(1, sizeof(*c));
    if (!c) {
        wm_close(win);
        return;
    }
    c->win = win;
    c->master = -1;
    c->rows = TERM_ROWS;
    c->screen = term_screen_create();
    if (!c->screen) {
        free(c);
        wm_close(win);
        return;
    }
    s_term = c;

    terminal_build_ui(c, content);
    feed_msg(c, "YeshenGui Terminal\nCtrl+W closes this window\n\n");
    spawn_shell(c);
    c->timer = lv_timer_create(terminal_timer_cb, TERM_TIMER_MS, c);
    terminal_refresh(c);
    wm_enable_bubble(content);
}

bool terminal_is_open(void)
{
    return s_term != NULL;
}

void terminal_close(void)
{
    if (!s_term) return;
    if (s_term->win) wm_close(s_term->win);
    else terminal_cleanup(s_term);
}

static void input_insert(term_ctx_t *c, char ch)
{
    if (c->input_len >= TERM_COLS) return;
    memmove(&c->input[c->input_cur + 1], &c->input[c->input_cur],
            (size_t)(c->input_len - c->input_cur));
    c->input[c->input_cur] = ch;
    c->input_len++;
    c->input_cur++;
    c->input[c->input_len] = '\0';
}

static void input_erase(term_ctx_t *c)
{
    if (c->input_cur <= 0) return;
    memmove(&c->input[c->input_cur - 1], &c->input[c->input_cur],
            (size_t)(c->input_len - c->input_cur));
    c->input_cur--;
    c->input_len--;
    c->input[c->input_len] = '\0';
}

static void input_commit(term_ctx_t *c)
{
    if (c->master >= 0 && c->input_len > 0) {
        ssize_t r = write(c->master, c->input, (size_t)c->input_len);
        (void)r;
    }
    if (c->master >= 0) {
        ssize_t r = write(c->master, "\r", 1);
        (void)r;
    }
    term_screen_feed(c->screen, c->input, (size_t)c->input_len);
    term_screen_feed(c->screen, "\r\n", 2);
    c->input_len = 0;
    c->input_cur = 0;
    c->input[0] = '\0';
}

void terminal_handle_key(const ui_key_t *key)
{
    if (!s_term || s_term->master < 0 || !key) return;
    term_ctx_t *c = s_term;

    switch (key->type) {
    case UI_KEY_CHAR:
        input_insert(c, key->ch);
        terminal_refresh(c);
        break;
    case UI_KEY_ENTER:
        input_commit(c);
        terminal_refresh(c);
        break;
    case UI_KEY_BACKSPACE:
        input_erase(c);
        terminal_refresh(c);
        break;
    case UI_KEY_LEFT:
        if (c->input_cur > 0) c->input_cur--;
        terminal_refresh(c);
        break;
    case UI_KEY_RIGHT:
        if (c->input_cur < c->input_len) c->input_cur++;
        terminal_refresh(c);
        break;
    case UI_KEY_TAB: {
        int stop = (c->input_cur + 4) & ~3;
        while (c->input_cur < stop) input_insert(c, ' ');
        terminal_refresh(c);
        break;
    }
    case UI_KEY_CTRL_C: {
        ssize_t r = write(c->master, "\x03", 1);
        (void)r;
        c->input_len = 0;
        c->input_cur = 0;
        c->input[0] = '\0';
        term_screen_feed(c->screen, "^C\r\n", 4);
        terminal_refresh(c);
        break;
    }
    case UI_KEY_CTRL_D: {
        ssize_t r = write(c->master, "\x04", 1);
        (void)r;
        break;
    }
    case UI_KEY_ESC: {
        ssize_t r = write(c->master, "\x1b", 1);
        (void)r;
        break;
    }
    default:
        break;
    }
}

void terminal_demo_feed(const char *utf8)
{
    if (!s_term || !s_term->screen || !utf8) return;
    term_screen_feed(s_term->screen, utf8, strlen(utf8));
    terminal_refresh(s_term);
}
